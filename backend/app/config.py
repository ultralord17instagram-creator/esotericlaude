from functools import lru_cache

from pydantic_settings import BaseSettings, SettingsConfigDict


class Settings(BaseSettings):
    # ── База данных ─────────────────────────────────────────────────────────────
    # PostgreSQL URL для asyncpg.
    # Источник: .env → DATABASE_URL
    # Формат: postgresql+asyncpg://user:password@host:5432/dbname
    database_url: str

    # ── Auth Service партнёрки (S2S интеграция) ──────────────────────────────────
    # URL auth_service куда ходить за верификацией токена.
    # Источник: уточнить у команды партнёрки при подключении оффера.
    auth_service_url: str

    # API-ключ оффера в auth_service — передаётся в заголовке X-Offer-Api-Key.
    # Источник: получить у команды партнёрки при регистрации оффера.
    # СЕКРЕТ — не коммитить в git.
    auth_service_api_key: str

    # ── Идентификатор оффера ─────────────────────────────────────────────────────
    # Строковый ID оффера в системе партнёрки (напр. "esotericvision").
    # Источник: получить у команды партнёрки при регистрации оффера.
    # Используется для логирования и идентификации оффера в своём коде.
    # В auth_service оффер определяется по API-ключу, но этот ID полезен
    # для логов, трекинга и отладки.
    offer_id: str

    # ── Payment Service партнёрки ────────────────────────────────────────────────
    # URL payment_service для получения тарифа оффера.
    # Источник: уточнить у команды партнёрки при подключении оффера.
    payment_service_url: str

    # ── Pay Form партнёрки ───────────────────────────────────────────────────────
    # URL платёжной формы, куда редиректить пользователя при оформлении подписки.
    # Источник: уточнить у команды партнёрки при подключении оффера.
    pay_form_url: str

    # ── Режим отладки ────────────────────────────────────────────────────────────
    # True: включает /docs, /redoc, подробные ошибки в ответах.
    # False (продакшн): документация недоступна, ошибки без деталей.
    debug: bool = False

    model_config = SettingsConfigDict(env_file=".env", env_file_encoding="utf-8")


@lru_cache(maxsize=1)
def get_settings() -> Settings:
    """Кешированный синглтон настроек. .env читается один раз при старте."""
    return Settings()
