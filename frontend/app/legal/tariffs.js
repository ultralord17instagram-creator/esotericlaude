export function rub(value) {
  return `${Number(value).toLocaleString('ru-RU')} ₽`
}

// «1 день», «3 дня», «7 дней»
export function days(n) {
  const abs = Math.abs(n) % 100
  const last = abs % 10
  if (abs > 10 && abs < 20) return `${n} дней`
  if (last === 1) return `${n} день`
  if (last >= 2 && last <= 4) return `${n} дня`
  return `${n} дней`
}
