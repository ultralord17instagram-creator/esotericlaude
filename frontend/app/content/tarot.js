// Pseudo-random but deterministic: seed from current date so same day = same cards.
function dayHash() {
  const d = new Date()
  return d.getFullYear() * 10000 + (d.getMonth() + 1) * 100 + d.getDate()
}

function pick(arr, seed) {
  return arr[(seed * 1103515245 + 12345) % arr.length]
}

